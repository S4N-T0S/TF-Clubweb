// Regenerates src/vault/lib/keysStatic.js, the vault's bundled copy of Embark's
// id -> name lookup, and cross-checks the hand-curated tables against it.
//
// Exports since 2026-09 ship `<id>_keys.jsonl` inside `<id>_persistence.zip`,
// naming only the ids THAT export references. This merges every key file under
// public/__verify/player_examples/ (loose, or still inside the zip), so the
// catalogue grows with each donor and older exports, which have no key file,
// decode against it too.
//
//   node tools/generate-vault-keys.mjs [extra-dir-or-file ...]
//
// Kept: what the vault resolves (weapons/gadgets/specializations, scorecard
// metrics, archetypes, maps, scenarios, seasons, account-wide progression tracks).
// Cosmetics are dropped: only 2026-09+ exports reference them, and those carry the
// name on the record. Per-item mastery tracks likewise: only those exports have the
// BucketID to look up, and they bring their own key file.
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { dirname, join, basename } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { unzipSync, strFromU8 } from 'fflate';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SAMPLES = join(ROOT, 'public', '__verify', 'player_examples');
const OUT = join(ROOT, 'src', 'vault', 'lib', 'keysStatic.js');
const lib = (f) => import(pathToFileURL(join(ROOT, 'src', 'vault', 'lib', f)).href);

const isKeysName = (p) => /keys\.(jsonl|json|txt)$/i.test(basename(p));
const walk = (p) => (statSync(p).isDirectory() ? readdirSync(p).flatMap((n) => walk(join(p, n))) : [p]);

// [{ label, text }] for every key file reachable from `paths`.
const sources = [];
for (const p of [SAMPLES, ...process.argv.slice(2)].flatMap(walk)) {
  if (isKeysName(p)) sources.push({ label: p, text: readFileSync(p, 'utf8') });
  else if (/persistence.*\.zip$/i.test(basename(p))) {
    for (const [name, bytes] of Object.entries(unzipSync(readFileSync(p), { filter: (f) => isKeysName(f.name) }))) {
      sources.push({ label: `${p}!${name}`, text: strFromU8(bytes) });
    }
  }
}
if (!sources.length) throw new Error(`No *_keys.jsonl found under ${SAMPLES}`);
// Oldest ticket first, so the newest export's wording wins a conflict.
const ticket = (s) => Number(/(\d+)_keys\./i.exec(s.label)?.[1] ?? 0);
sources.sort((a, b) => ticket(a) - ticket(b));

const clean = (s) => (typeof s === 'string' ? s.replace(/''/g, "'") : s); // the export doubles apostrophes
const KEEP_KINDS = new Set(['Scorecard', 'Archetype']);
const SHAPES = {
  TheFinalsItemKey: { id: 'GameAssetID', fields: ['GameAssetID', 'Name', 'Kind', 'ItemType', 'ItemSubType', 'AssetName'], keep: (r) => r.ItemType === 'GameItem' || KEEP_KINDS.has(r.Kind) },
  TheFinalsMapKey: { id: 'MapVariant', fields: ['MapVariant', 'MapName', 'VariantName'] },
  TheFinalsScenarioKey: { id: 'ScenarioID', fields: ['ScenarioID', 'Name', 'InternalName', 'GameMode'] },
  TheFinalsSeasonKey: { id: 'SeasonID', fields: ['SeasonID', 'SeasonNumber', 'Name', 'StartDate', 'EndDate'] },
  TheFinalsMasteryKey: { id: 'BucketID', fields: ['BucketID', 'Category', 'Name', 'GameAssetID'], keep: (r) => r.Category !== 'Item mastery' && r.Category !== 'Progressive item' },
};

const merged = Object.fromEntries(Object.keys(SHAPES).map((t) => [t, new Map()]));
const renamed = [];
for (const src of sources) {
  for (const line of src.text.split('\n')) {
    if (!line.trim()) continue;
    let obj;
    try { obj = JSON.parse(line); } catch { continue; }
    const type = Object.keys(obj)[0];
    const shape = SHAPES[type];
    const r = obj[type];
    if (!shape || !r || r.Resolved === false || r[shape.id] == null || (shape.keep && !shape.keep(r))) continue;
    const rec = {};
    for (const f of shape.fields) if (r[f] != null && r[f] !== '') rec[f] = clean(r[f]);
    const id = String(r[shape.id]);
    const prev = merged[type].get(id);
    const nameOf = (x) => x.Name ?? x.MapName;
    if (prev && nameOf(prev) !== nameOf(rec)) renamed.push(`${type} ${id}: "${nameOf(prev)}" -> "${nameOf(rec)}"`);
    merged[type].set(id, rec);
  }
}

const body = Object.entries(merged)
  .map(([type, map]) => {
    const rows = [...map.entries()].sort((a, b) => a[0].localeCompare(b[0], 'en', { numeric: true })).map(([, r]) => `    ${JSON.stringify(r)},`);
    return `  ${type}: [\n${rows.join('\n')}\n  ],`;
  })
  .join('\n');
const tickets = [...new Set(sources.map(ticket).filter(Boolean))];
writeFileSync(OUT, `// GENERATED by tools/generate-vault-keys.mjs from Embark's <id>_keys.jsonl files. Do not edit by hand.\nexport default {\n  sources: ${JSON.stringify(tickets)},\n${body}\n};\n`);

console.log(`Read ${sources.length} key file(s): tickets ${tickets.join(', ')}`);
for (const [type, map] of Object.entries(merged)) console.log(`  ${String(map.size).padStart(5)}  ${type}`);
console.log(`Wrote ${OUT} (${statSync(OUT).size.toLocaleString()} bytes)`);
if (renamed.length) console.log(`\nRenamed between exports (newest kept):\n  ${renamed.join('\n  ')}`);

// --- cross-check the curated tables -----------------------------------------
// Embark's names are the authority on WHAT an id is; the curated tables add what
// the keys lack (archetype, icons, mode category, lobby size). Anything printed
// below is a curated entry to fix, or a new id to curate.
const { WEAPONS } = await lib('weapons.js');
const { scenarioFromKey, SCENARIO_MODES } = await lib('gameMeta.js');
const { MAPS } = await lib('maps.js');
const { SEASONS } = await lib('seasons.js');
const norm = (s) => String(s ?? '').toLowerCase().replace(/[^a-z0-9]/g, '');
// Curated names that differ from Embark's on purpose.
const INTENTIONAL_NAMES = new Set([
  '-2046791033', // the Blast Off! LTM launcher; Embark calls it plain "RPG-7", same as the Heavy gadget
]);
const issues = [];

for (const [id, k] of merged.TheFinalsItemKey) {
  if (k.ItemType !== 'GameItem') continue;
  const w = Object.hasOwn(WEAPONS, id) ? WEAPONS[id] : null;
  if (w && norm(w.name) !== norm(k.Name) && !INTENTIONAL_NAMES.has(id)) issues.push(`weapon ${id}: curated "${w.name}" but Embark says "${k.Name}" (${k.ItemSubType}, ${k.AssetName})`);
  if (!w && k.ItemSubType === 'Weapon') issues.push(`weapon ${id}: "${k.Name}" (${k.AssetName}) is not in WEAPONS. Add it with its archetype.`);
}
for (const [id, k] of merged.TheFinalsScenarioKey) {
  const viaKey = scenarioFromKey({ name: k.Name, gameMode: k.GameMode });
  if (!viaKey.translated) issues.push(`scenario ${id}: no translation for Embark name "${k.Name}" (${k.GameMode}). Add it to EMBARK_SCENARIOS.`);
  const cur = Object.hasOwn(SCENARIO_MODES, id) ? SCENARIO_MODES[id] : null;
  if (cur && viaKey.translated && (cur.label !== viaKey.label || cur.category !== viaKey.category)) issues.push(`scenario ${id}: curated "${cur.label}" [${cur.category}] vs Embark "${k.Name}" -> "${viaKey.label}" [${viaKey.category}]`);
}
for (const [mv, k] of merged.TheFinalsMapKey) {
  const m = /^DA_MV_([A-Za-z]+)_(\d+)/.exec(mv);
  const cur = m && MAPS[`${m[1]}_${m[2]}`];
  if (!cur) issues.push(`map ${mv}: "${k.MapName}" has no MAPS entry`);
}
for (const [id, k] of merged.TheFinalsSeasonKey) {
  if (!SEASONS.some((s) => s.n === k.SeasonNumber)) issues.push(`season ${id}: S${k.SeasonNumber} (${k.StartDate}) is not in seasons.js`);
}
console.log(issues.length ? `\n${issues.length} thing(s) to curate:\n  ${issues.join('\n  ')}` : '\nCurated tables agree with every key.');
